import * as fs from 'node:fs';
import * as path from 'node:path';
import * as url from 'node:url';

import { build } from 'esbuild';

/**
 * Bundles the `soat-design` React primitives into `_ds_bundle.js`, the script
 * the specimen cards load after React from a CDN. The components import
 * `react`; the bundle resolves it to the page's `window.React` so the cards
 * and the components share one React.
 *
 * `tests/harness/designSkillReferences.test.mjs` rebuilds in memory and fails
 * when the committed bundle differs.
 */

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));

export const DESIGN_DIR = path.resolve(
  __dirname,
  '../.claude/skills/soat-design'
);

export const DESIGN_BUNDLE = path.join(DESIGN_DIR, '_ds_bundle.js');

/** The global the cards destructure: `window.SOATDesignSystem_de1198`. */
const GLOBAL_NAME = 'SOATDesignSystem_de1198';

const COMPONENTS_DIR = path.join(DESIGN_DIR, 'components');

const listComponents = (dir) => {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) return listComponents(full);
      return entry.name.endsWith('.jsx') ? [full] : [];
    })
    .sort();
};

const reactFromWindow = {
  name: 'react-from-window',
  setup: (pluginBuild) => {
    pluginBuild.onResolve({ filter: /^react$/ }, () => {
      return { path: 'react', namespace: 'react-from-window' };
    });
    pluginBuild.onLoad({ filter: /.*/, namespace: 'react-from-window' }, () => {
      return { contents: 'module.exports = window.React;', loader: 'js' };
    });
  },
};

export const buildDesignBundle = async () => {
  const entry = listComponents(COMPONENTS_DIR)
    .map((file) => {
      const relative = path
        .relative(DESIGN_DIR, file)
        .split(path.sep)
        .join('/');
      return `export * from './${relative}';`;
    })
    .join('\n');

  const result = await build({
    stdin: { contents: entry, resolveDir: DESIGN_DIR, loader: 'js' },
    bundle: true,
    format: 'iife',
    globalName: GLOBAL_NAME,
    jsx: 'transform',
    loader: { '.jsx': 'jsx' },
    legalComments: 'none',
    charset: 'utf8',
    target: 'es2020',
    write: false,
    plugins: [reactFromWindow],
    banner: {
      js: '/* Generated by scripts/buildDesignBundle.mjs from the .jsx files under components/. Do not edit. */',
    },
  });

  return result.outputFiles[0].text;
};

if (process.argv[1] === url.fileURLToPath(import.meta.url)) {
  fs.writeFileSync(DESIGN_BUNDLE, await buildDesignBundle());
}
