import * as fs from 'node:fs';

type ServerErrorCodes = Record<string, { httpStatus: number }>;

/**
 * The server registry reduced to what a client branches on: the status each
 * code answers with. Descriptions stay in the published API reference.
 */
export const sdkErrorCodes = (args: { codes: ServerErrorCodes }) => {
  return Object.fromEntries(
    Object.entries(args.codes).map(([code, { httpStatus }]) => {
      return [code, { httpStatus }];
    })
  );
};

export const writeErrorCodes = (args: {
  codes: ServerErrorCodes;
  outputFile: string;
}) => {
  const codes = JSON.stringify(sdkErrorCodes({ codes: args.codes }), null, 2);
  fs.writeFileSync(
    args.outputFile,
    [
      '// Generated by scripts/generate.ts from the server ERROR_CODES registry.',
      `export const ERROR_CODES = ${codes} as const;`,
      '',
      'export type ErrorCode = keyof typeof ERROR_CODES;',
      '',
    ].join('\n')
  );
};
